<?php

declare(strict_types=1);

namespace App\Modules\InventoryAnalytics\Domain;

enum AbcXyzGroup: string
{
    case AX = 'AX';
    case AY = 'AY';
    case AZ = 'AZ';
    case BX = 'BX';
    case BY = 'BY';
    case BZ = 'BZ';
    case CX = 'CX';
    case CY = 'CY';
    case CZ = 'CZ';

    public function abcClass(): AbcClass
    {
        return AbcClass::from(substr($this->value, 0, 1));
    }

    public function xyzClass(): XyzClass
    {
        return XyzClass::from(substr($this->value, 1, 1));
    }

    public function label(): string
    {
        return match ($this) {
            self::AX => 'Высокий оборот, стабильный спрос',
            self::AY => 'Высокий оборот, сезонный спрос',
            self::AZ => 'Высокий оборот, нерегулярный спрос',
            self::BX => 'Средний оборот, стабильный спрос',
            self::BY => 'Средний оборот, сезонный спрос',
            self::BZ => 'Средний оборот, нерегулярный спрос',
            self::CX => 'Низкий оборот, стабильный спрос',
            self::CY => 'Низкий оборот, сезонный спрос',
            self::CZ => 'Низкий оборот, нерегулярный спрос',
        };
    }

    public function description(): string
    {
        return match ($this) {
            self::AX => 'Флагманы продаж с устойчивым потреблением. Формируют основную выручку бизнеса при высокой точности прогноза.',
            self::AY => 'Ключевые товары с выраженными сезонными или периодическими колебаниями. Высокий вклад в выручку.',
            self::AZ => 'Высокодоходные товары с редкими или крупными оптовыми заказами. Высокий риск упущенной выгоды при дефиците.',
            self::BX => 'Надёжные товары второго эшелона со стабильной реализацией.',
            self::BY => 'Товары средней значимости с волнообразным расходом.',
            self::BZ => 'Товары со средней выручкой и низкой предсказуемостью реализации.',
            self::CX => 'Недорогие расходники и сопутствующие товары с постоянным спросом.',
            self::CY => 'Мелкие товары с сезонным характером продаж.',
            self::CZ => 'Неликвидные позиции, единичные заказы или товары без движения.',
        };
    }

    public function recommendation(): string
    {
        return match ($this) {
            self::AX => 'Автоматическое пополнение точно в срок (JIT), минимальный страховой запас, ежедневный мониторинг остатка.',
            self::AY => 'Планирование поставок по сезонным коэффициентам, средний страховой запас к началу пика сезона.',
            self::AZ => 'Индивидуальный контроль заказов, повышенный страховой запас или работа по предзаказу.',
            self::BX => 'Стандартный цикл заказа, поддержание неснижаемого остатка на складе.',
            self::BY => 'Адаптивный страховой запас, пополнение партиями с учетом динамики продаж.',
            self::BZ => 'Контроль закупки, ограничение объема партий во избежание заморозки оборотных средств.',
            self::CX => 'Заказ крупными партиями раз в несколько месяцев для снижения логистических затрат.',
            self::CY => 'Закупка строго к началу сезона, распродажа остатков в конце периода.',
            self::CZ => 'Вывод из постоянного складского ассортимента, работа под заказ, списание или ликвидация неликвидов.',
        };
    }
}
